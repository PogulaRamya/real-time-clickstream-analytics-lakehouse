CREATE WAREHOUSE IF NOT EXISTS CLICKSTREAM_WH WAREHOUSE_SIZE='XSMALL' AUTO_SUSPEND=60 AUTO_RESUME=TRUE INITIALLY_SUSPENDED=TRUE;
CREATE DATABASE IF NOT EXISTS CLICKSTREAM;
CREATE SCHEMA IF NOT EXISTS CLICKSTREAM.RAW;
CREATE SCHEMA IF NOT EXISTS CLICKSTREAM.ANALYTICS;
CREATE ROLE IF NOT EXISTS CLICKSTREAM_LOADER;
CREATE ROLE IF NOT EXISTS CLICKSTREAM_TRANSFORMER;
CREATE ROLE IF NOT EXISTS CLICKSTREAM_READER;
GRANT USAGE ON WAREHOUSE CLICKSTREAM_WH TO ROLE CLICKSTREAM_LOADER;
GRANT USAGE ON WAREHOUSE CLICKSTREAM_WH TO ROLE CLICKSTREAM_TRANSFORMER;
GRANT USAGE ON WAREHOUSE CLICKSTREAM_WH TO ROLE CLICKSTREAM_READER;
GRANT USAGE ON DATABASE CLICKSTREAM TO ROLE CLICKSTREAM_LOADER;
GRANT USAGE ON DATABASE CLICKSTREAM TO ROLE CLICKSTREAM_TRANSFORMER;
GRANT USAGE ON DATABASE CLICKSTREAM TO ROLE CLICKSTREAM_READER;
GRANT USAGE ON SCHEMA CLICKSTREAM.RAW TO ROLE CLICKSTREAM_LOADER;
GRANT CREATE TABLE, CREATE STAGE, CREATE FILE FORMAT ON SCHEMA CLICKSTREAM.RAW TO ROLE CLICKSTREAM_LOADER;
GRANT USAGE ON SCHEMA CLICKSTREAM.RAW TO ROLE CLICKSTREAM_TRANSFORMER;
GRANT SELECT ON ALL TABLES IN SCHEMA CLICKSTREAM.RAW TO ROLE CLICKSTREAM_TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA CLICKSTREAM.RAW TO ROLE CLICKSTREAM_TRANSFORMER;
GRANT USAGE ON SCHEMA CLICKSTREAM.ANALYTICS TO ROLE CLICKSTREAM_TRANSFORMER;
GRANT CREATE TABLE, CREATE VIEW ON SCHEMA CLICKSTREAM.ANALYTICS TO ROLE CLICKSTREAM_TRANSFORMER;
GRANT USAGE ON SCHEMA CLICKSTREAM.ANALYTICS TO ROLE CLICKSTREAM_READER;
GRANT SELECT ON ALL TABLES IN SCHEMA CLICKSTREAM.ANALYTICS TO ROLE CLICKSTREAM_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA CLICKSTREAM.ANALYTICS TO ROLE CLICKSTREAM_READER;
GRANT SELECT ON ALL VIEWS IN SCHEMA CLICKSTREAM.ANALYTICS TO ROLE CLICKSTREAM_READER;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA CLICKSTREAM.ANALYTICS TO ROLE CLICKSTREAM_READER;
